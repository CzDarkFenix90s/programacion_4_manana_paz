fun main() {
  println("Operadores de Comparacion")
  val num1 = 15
  val num2 = 10
  println("$num1 == $num2 = ${num1==num2}")
  println("$num1 .equals $num2 = ${num1.equals(num2)}")
  println("$num1 != $num2 = ${num1!=num2}")
  println("$num1 > $num2 = ${num1>num2}")
  println("$num1 >= $num2 = ${num1>=num2}")
  println("$num1 < $num2 = ${num1<num2}")
  println("$num1 <= $num2 = ${num1<=num2}")
  
}

fun main() {
  println("Operadores de Comparacion")
  val capacidadBus1 = 15
  val capacidadBus2 = 10
  println("$capacidadBus1 == $capacidadBus2 = ${capacidadBus1==capacidadBus2}")
  println("$capacidadBus1 .equals $capacidadBus2 = ${capacidadBus1.equals(capacidadBus2)}")
  println("$capacidadBus1 != $capacidadBus2 = ${capacidadBus1!=capacidadBus2}")
  println("$capacidadBus1 > $capacidadBus2 = ${capacidadBus1>capacidadBus2}")
  println("$capacidadBus1 >= $capacidadBus2 = ${capacidadBus1>=capacidadBus2}")
  println("$capacidadBus1 < $capacidadBus2 = ${capacidadBus1<capacidadBus2}")
  println("$capacidadBus1 <= $capacidadBus2 = ${capacidadBus1<=capacidadBus2}")
  
}

        Row(children: [
          Expanded(child: _TarjetaMetrica(titulo: 'Pacientes', valor: '8',  icono: Icons.restaurant,          color: cs.primaryContainer)),
          const SizedBox(width: 8),
          Expanded(child: _TarjetaMetrica(titulo: 'Observaciones',    valor: '3',  icono: Icons.notifications, color: cs.errorContainer)),
